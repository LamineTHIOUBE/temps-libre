<?php

/* =========================================================
   DÉMARRER LA SESSION
   ========================================================= */

session_start();


/* =========================================================
   DÉTRUIRE LES VARIABLES DE SESSION
   ========================================================= */

$_SESSION = [];


/* =========================================================
   DÉTRUIRE LE COOKIE DE SESSION
   ========================================================= */

if (ini_get("session.use_cookies")) {

    $params = session_get_cookie_params();

    setcookie(
        session_name(),
        '',
        time() - 42000,
        $params["path"],
        $params["domain"],
        $params["secure"],
        $params["httponly"]
    );

}


/* =========================================================
   DÉTRUIRE LA SESSION
   ========================================================= */

session_destroy();


/* =========================================================
   RETOUR À LA CONNEXION
   ========================================================= */

header("Location: login.php");

exit;
